"""A TTF -> the firmware's font format (felucca_font_t, 4-bit alpha), FONT_S (16 px line) and FONT_L (32 px line).
   python3 tools/gen_font_ttf.py FONT.ttf WEIGHT CAP_S CAP_L OUT.h [TRACK]   (needs Pillow)
   The font in firmware/gen/felucca_font.h (OrGigs 2):
   python3 tools/gen_font_ttf.py assets/fonts/VarelaRound-Regular.ttf 400 9 20 firmware/gen/felucca_font.h"""
import sys
from PIL import Image, ImageDraw, ImageFont

path, weight, cap_s, cap_l, out = sys.argv[1], int(sys.argv[2]), float(sys.argv[3]), float(sys.argv[4]), sys.argv[5]
TRACK = float(sys.argv[6]) if len(sys.argv) > 6 else 0.6   # letter spacing, px at a 10 px cap


def load(px):
    f = ImageFont.truetype(path, px)
    try:
        axes = f.get_variation_axes()
        f.set_variation_by_axes([weight if a.get("name", b"") in (b"Weight", "Weight") else a["default"] for a in axes])
    except Exception:
        pass
    return f


def sized(cap):
    for px in range(8, 80):
        f = load(px)
        b = f.getbbox("H")
        if b[3] - b[1] >= cap:
            return f
    return f


def font(name, cap, h, base, last):
    f, pad = sized(cap), 2
    adv, bw, off, data = [], [], [], []
    for ch in range(32, last + 1):
        a = max(5 if ch == 32 else 1, round(f.getlength(chr(ch)) + TRACK * cap / 10))
        w = a + 2 * pad
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((pad, base), chr(ch), font=f, fill=255, anchor="ls")
        bpr = (w + 1) // 2
        off.append(len(data))
        for y in range(h):
            row = [img.getpixel((x, y)) * 15 // 255 for x in range(w)] + [0]
            for x in range(0, w, 2):
                data.append(row[x] << 4 | row[x + 1])
        adv.append(a)
        bw.append(w)
    n = last - 31
    c = lambda t, v: "static const %s %s[%d] = {%s};\n" % (t, name + v[0], len(v[1]), ", ".join(map(str, v[1])))
    return (c("uint8_t", ("_DATA", data)) + c("uint16_t", ("_OFF", off)) + c("uint8_t", ("_ADV", adv))
            + c("uint8_t", ("_BW", bw))
            + "static const felucca_font_t %s = { %d, %d, 32, %d, %s_ADV, %s_BW, %s_OFF, %s_DATA };\n" % (name, h, pad, last, name, name, name, name))


with open(out, "w") as o:
    o.write("/* generated by tools/gen_font_ttf.py from %s (SIL OFL 1.1, assets/fonts) */\n#pragma once\n#include <stdint.h>\n" % path.split("/")[-1])
    o.write(font("FONT_S", cap_s, 16, 13, 126))
    o.write(font("FONT_L", cap_l, 32, 26, 95))
print(out)
