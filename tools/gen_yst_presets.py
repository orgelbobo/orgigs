"""The Yamaha SEQTRAK's sound list for core/orgigs_yst.c: assets/seqtrak/presets.csv (jaeggerr/seqtrak-docs,
MIT, assets/seqtrak/LICENSE.seqtrak-docs) -> firmware/gen/yst_presets.h.

Drum, Synth and DX share the numbers 1..2032 (bank MSB 63, LSB = (n-1) / 128, program = (n-1) % 128); the
sampler has its own 1..392 (MSB 62). The names go into one string pool, each sound gets its offset and category.

  python3 tools/gen_yst_presets.py
"""
import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "seqtrak", "presets.csv")
OUT = os.path.join(ROOT, "firmware", "gen", "yst_presets.h")


def c_str(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main():
    rows = list(csv.DictReader(open(SRC, newline="")))
    main_ = sorted((r for r in rows if r["bank_msb"] == "63"), key=lambda r: int(r["number"]))
    smp = sorted((r for r in rows if r["bank_msb"] == "62"), key=lambda r: int(r["number"]))
    assert [int(r["number"]) for r in main_] == list(range(1, len(main_) + 1)), "MSB 63: numbers 1..n"
    assert [int(r["number"]) for r in smp] == list(range(1, len(smp) + 1)), "MSB 62: numbers 1..n"
    for r in rows:
        assert int(r["bank_lsb"]) * 128 + int(r["program"]) == int(r["number"]) - 1, r
    first = {}
    for r in main_:
        first.setdefault(r["engine"], int(r["number"]))
    cats = sorted({r["category"] for r in rows})
    pool, off = [], {}
    at = 0
    for r in main_ + smp:
        key = r["name"]
        if key not in off:
            off[key] = at
            pool.append(key)
            at += len(key.encode("ascii")) + 1
    assert at < 65536
    o = ["/* generated by tools/gen_yst_presets.py from assets/seqtrak/presets.csv (jaeggerr/seqtrak-docs, MIT):",
         " * the Yamaha SEQTRAK's sounds. Do not edit. */",
         f"#define YST_N63 {len(main_)}u                /* drum, synth, DX: 1..{len(main_)}, bank MSB 63 */",
         f"#define YST_NSMP {len(smp)}u                /* the sampler: 1..{len(smp)}, bank MSB 62 */",
         f"#define YST_DRUM1 {first['Drum']}u",
         f"#define YST_SYNTH1 {first['Synth']}u",
         f"#define YST_DX1 {first['DX']}u",
         f"#define YST_NCAT {len(cats)}u",
         "static const char *const YST_CAT[YST_NCAT] = {"]
    o += [f'    "{c_str(c)}",' for c in cats]
    o += ["};", "static const char YST_NAMES[] ="]
    line = "    "
    for name in pool:
        piece = f'"{c_str(name)}\\0"'
        if len(line) + len(piece) > 116:
            o.append(line)
            line = "    "
        line += piece
    o.append(line + ";")
    for tag, lst in (("63", main_), ("SMP", smp)):
        o.append(f"static const uint16_t YST_OFF{tag}[] = {{")
        vals = [str(off[r["name"]]) for r in lst]
        o += ["    " + ", ".join(vals[i:i + 16]) + "," for i in range(0, len(vals), 16)]
        o.append("};")
        o.append(f"static const uint8_t YST_CAT{tag}[] = {{")
        vals = [str(cats.index(r["category"])) for r in lst]
        o += ["    " + ", ".join(vals[i:i + 32]) + "," for i in range(0, len(vals), 32)]
        o.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(o) + "\n")
    print(f"{OUT}: {len(main_)} + {len(smp)} sounds, {at} bytes of names, {len(cats)} categories")


if __name__ == "__main__":
    main()
