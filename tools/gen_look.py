"""Generate firmware/gen/orgigs_look.h: the tables behind OrGigs 2's look (firmware/board/look.c).

  LOOK_PANEL   the smoked glass over dark wood behind the screens, rows 24..179, RGB565
  LOOK_SH/SP   a drawbar shaft across its width (64 steps): the shading (Q8) and the shine (Q8)

The FM-1 has no FPU: the curves are computed here once.

  python3 tools/gen_look.py            (-> firmware/gen/orgigs_look.h)
"""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "firmware" / "gen" / "orgigs_look.h"
Y0, Y1 = 24, 180


def mix(a, b, t):
    return tuple(x + (y - x) * t for x, y in zip(a, b))


def rgb565(c):
    r, g, b = (max(0, min(255, int(v))) for v in c)
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3


def panel():
    out = []
    for y in range(Y0, Y1):
        for x in range(240):
            t = (y - Y0) / (Y1 - Y0)
            c = mix((30, 22, 18), (8, 7, 8), t)
            s = 0.5 + 0.25 * math.sin(x * 0.045 + y * 0.03) + 0.25 * math.sin(x * 0.017 - y * 0.06 + 1.3)
            c = tuple(v * (0.85 + 0.3 * s) for v in c)
            band = (x + y * 0.7) - 150
            band = math.exp(-band * band / 900.0)
            out.append(rgb565(mix(c, (120, 110, 100), 0.07 * band)))
    return out


def shaft():
    sh, sp = [], []
    for i in range(64):
        u = (i + 0.5) / 64
        sh.append(round(256 * (0.42 + 0.7 * math.sin(math.pi * u) ** 0.7)))
        sp.append(round(256 * 0.45 * math.exp(-((u - 0.3) / 0.09) ** 2)))
    return sh, sp


def table(t, name, v, per=16):
    rows = [", ".join(str(x) for x in v[i:i + per]) for i in range(0, len(v), per)]
    return "static const %s %s[%d] = {\n    %s,\n};\n" % (t, name, len(v), ",\n    ".join(rows))


def main():
    sh, sp = shaft()
    s = ["/* generated by tools/gen_look.py: the tables behind OrGigs 2's look (firmware/board/look.c) */",
         "#pragma once", "#include <stdint.h>",
         "#define LOOK_Y0 %d                    /* the panel's first screen row */" % Y0,
         "#define LOOK_Y1 %d                   /* (and the one after its last) */" % Y1, ""]
    s.append(table("uint16_t", "LOOK_PANEL", panel()))
    s.append(table("uint16_t", "LOOK_SH", sh))
    s.append(table("uint16_t", "LOOK_SP", sp))
    OUT.write_text("\n".join(s))
    print(OUT)


if __name__ == "__main__":
    main()
